CREATE TABLE partners (
    partner_id INT GENERATED BY DEFAULT AS IDENTITY,
    partner_name VARCHAR(200) NOT NULL,
    inn VARCHAR(12) NOT NULL,
    email VARCHAR(254) NOT NULL,
    CONSTRAINT pk_partners PRIMARY KEY (partner_id),
    CONSTRAINT uq_partners_inn UNIQUE (inn),
    CONSTRAINT uq_partners_email UNIQUE (email),
    CONSTRAINT ck_partners_id CHECK (partner_id > 0),
    CONSTRAINT ck_partners_name CHECK (partner_name = btrim(partner_name) AND partner_name <> ''),
    CONSTRAINT ck_partners_inn CHECK (inn ~ '^([0-9]{10}|[0-9]{12})$'),
    CONSTRAINT ck_partners_email CHECK (
        email = lower(btrim(email))
        AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    )
);

CREATE TABLE products (
    product_id INT GENERATED BY DEFAULT AS IDENTITY,
    product_name VARCHAR(200) NOT NULL,
    price DECIMAL(14,2) NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT ck_products_id CHECK (product_id > 0),
    CONSTRAINT ck_products_name CHECK (product_name = btrim(product_name) AND product_name <> ''),
    CONSTRAINT ck_products_price CHECK (price >= 0 AND price <> 'NaN'::numeric)
);

CREATE TABLE sales_history (
    sale_id INT GENERATED BY DEFAULT AS IDENTITY,
    partner_id INT NOT NULL,
    product_id INT NOT NULL,
    sale_date DATE NOT NULL,
    quantity INT NOT NULL,
    unit_price DECIMAL(18,4) NOT NULL,
    CONSTRAINT pk_sales_history PRIMARY KEY (sale_id),
    CONSTRAINT fk_sales_history_partner FOREIGN KEY (partner_id)
        REFERENCES partners (partner_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_sales_history_product FOREIGN KEY (product_id)
        REFERENCES products (product_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_sales_history_id CHECK (sale_id > 0),
    CONSTRAINT ck_sales_history_quantity CHECK (quantity > 0),
    CONSTRAINT ck_sales_history_unit_price CHECK (unit_price >= 0 AND unit_price <> 'NaN'::numeric),
    CONSTRAINT ck_sales_history_date CHECK (isfinite(sale_date))
);

CREATE INDEX ix_sales_history_partner_date ON sales_history (partner_id, sale_date);
CREATE INDEX ix_sales_history_product ON sales_history (product_id);

CREATE VIEW sales_history_details AS
SELECT s.sale_id, s.partner_id, p.partner_name, s.product_id, pr.product_name,
       s.sale_date, s.quantity, s.unit_price,
       round(s.quantity * s.unit_price, 2) AS amount
FROM sales_history AS s
JOIN partners AS p ON p.partner_id = s.partner_id
JOIN products AS pr ON pr.product_id = s.product_id;

COMMENT ON COLUMN products.price IS 'Текущая справочная цена товара';
COMMENT ON COLUMN sales_history.unit_price IS 'Цена на дату продажи, восстановленная из исходной суммы и количества';
COMMENT ON VIEW sales_history_details IS 'Сумма продажи вычисляется, а не хранится повторно';
